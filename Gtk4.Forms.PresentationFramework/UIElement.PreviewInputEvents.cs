using System.Windows.Input;

namespace System.Windows;

/// <summary>CLR events for the tunnelling Preview* input events declared in <c>UIElement.InputEvents.cs</c>.</summary>
public abstract partial class UIElement
{
	/// <summary>Occurs when a key is pressed (tunnel phase).</summary>
	public event KeyEventHandler PreviewKeyDown
	{
		add => AddHandler(PreviewKeyDownEvent, value);
		remove => RemoveHandler(PreviewKeyDownEvent, value);
	}

	/// <summary>Occurs when a key is released (tunnel phase).</summary>
	public event KeyEventHandler PreviewKeyUp
	{
		add => AddHandler(PreviewKeyUpEvent, value);
		remove => RemoveHandler(PreviewKeyUpEvent, value);
	}

	/// <summary>Occurs when text is generated by a key stroke or IME (tunnel phase).</summary>
	public event TextCompositionEventHandler PreviewTextInput
	{
		add => AddHandler(PreviewTextInputEvent, value);
		remove => RemoveHandler(PreviewTextInputEvent, value);
	}
}
