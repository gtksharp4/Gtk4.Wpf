namespace System.Windows;

/// <summary>Specifies the display state of a <see cref="Window"/>.</summary>
public enum WindowState
{
	/// <summary>The window is in its normal (restored) state.</summary>
	Normal,
	/// <summary>The window is minimized to the taskbar.</summary>
	Minimized,
	/// <summary>The window is maximized to fill the available working area.</summary>
	Maximized,
}
