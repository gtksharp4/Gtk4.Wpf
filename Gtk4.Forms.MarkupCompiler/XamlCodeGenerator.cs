using System;
using System.Collections.Generic;
using System.IO;
using System.Text;
using System.Xml;
using System.Xml.Linq;

namespace Gtk4.Forms.MarkupCompiler
{
	/// <summary>
	/// Pure, unit-testable core: parses a WPF XAML document and emits the
	/// <c>InitializeComponent</c> partial class (C# source text).
	/// No MSBuild, no System.Xaml dependency.
	/// <para>
	/// <c>{StaticResource}</c> scope: an element's own <c>Resources</c> are emitted before its attributes and
	/// children, so a key in an ancestor's Resources is visible to every descendant regardless of textual
	/// order (WPF would fail on such a forward reference). Within one dictionary, entries resolve in document
	/// order, so a forward reference there still fails at run time as in WPF.
	/// </para>
	/// </summary>
	public partial class XamlCodeGenerator : IDisposable
	{
		DpSymbolResolver _resolver = new DpSymbolResolver(null);
		IXmlnsDefinitionSource _xmlnsSource = EmptyXmlnsDefinitionSource.Instance;

		/// <summary>
		/// Supplies the reference-assembly search paths that the resolver uses to
		/// distinguish DependencyProperty fields from plain CLR properties.
		/// Must be called before <see cref="Generate"/> when reference paths are available.
		/// </summary>
		public void SetReferencePaths(IReadOnlyList<string> paths)
		{
			_resolver?.Dispose();
			_resolver = new DpSymbolResolver(paths);
		}

		/// <summary>
		/// Supplies the XML-namespace→CLR-namespace mapping read from the referenced assemblies'
		/// <c>[assembly: XmlnsDefinition]</c> attributes.  When set, element types are resolved
		/// via the xmlns-definition source (with <see cref="WpfXmlnsMap"/> as fallback for known
		/// WPF types).  Call before <see cref="Generate"/>.
		/// </summary>
		internal void SetXmlnsDefinitionSource(IXmlnsDefinitionSource source)
		{
			_xmlnsSource = source ?? EmptyXmlnsDefinitionSource.Instance;
		}

		/// <inheritdoc />
		public void Dispose() => _resolver?.Dispose();

		/// <summary>
		/// Generates the <c>.g.cs</c> source for <paramref name="xaml"/>.
		/// </summary>
		/// <param name="xaml">Raw XAML text.</param>
		/// <param name="className">
		/// Receives the fully-qualified class name (e.g. <c>MyApp.MainWindow</c>), or
		/// <c>null</c> when <c>x:Class</c> is absent.
		/// </param>
		/// <returns>Generated C# source text, or <c>null</c> when nothing should be emitted.</returns>
		public string Generate(string xaml, out string className) =>
			Generate(xaml, out className, null, null);

		/// <summary>
		/// As <see cref="Generate(string, out string)"/>; a <c>Page</c>/<c>Window</c> root without
		/// <c>x:Class</c> gets a class named after <paramref name="xamlPath"/> in <paramref name="rootNamespace"/>.
		/// </summary>
		public string Generate(string xaml, out string className, string xamlPath, string rootNamespace)
		{
			if (xaml == null) throw new ArgumentNullException(nameof(xaml));

			XDocument doc;
			try
			{
				doc = XDocument.Parse(xaml, LoadOptions.PreserveWhitespace | LoadOptions.SetLineInfo);
			}
			catch (XmlException ex)
			{
				throw new XamlCodeGeneratorException("XAML parse error: " + ex.Message, ex);
			}

			_messages.Clear();
			XElement root = doc.Root;
			if (root == null)
			{
				className = null;
				return null;
			}

			NormalizeMarkupAttributes(root);
			XNamespace xNs = GetXNamespace(root);
			_xNs = xNs;
			_prefixMap = CollectXmlnsPrefixMap(root);
			_ignorableNamespaces = CollectIgnorableNamespaces(root);
			NormalizeBaseQualifiedPropertyElements(root);
			UnwrapExplicitCollections(root);
			XAttribute classAttr = root.Attribute(xNs + "Class");
			string implicitBase = null;
			className = classAttr?.Value.Trim() ?? ImplicitClass(root, xamlPath, rootNamespace, out implicitBase);
			string rootBase = RootBaseFor(root, classAttr != null, className);
			if (className == null) return null;
			if (implicitBase != null && UserClassExists(className)) className = InternalClassName(className, xamlPath);

			_scopeVars.Clear();
			CollectTypeKeyRefs(xaml);
			_classFqName = "global::" + className;
			int lastDot = className.LastIndexOf('.');
			string ns = lastDot >= 0 ? className.Substring(0, lastDot) : string.Empty;
			string typeName = lastDot >= 0 ? className.Substring(lastDot + 1) : className;

			_rootIsDictionary = IsDictionaryRoot(root);
			bool isAppDef = IsApplicationRoot(root);
			_registerNames = !isAppDef && !_rootIsDictionary;

			var sb = new StringBuilder();
			var w = new IndentedWriter(sb);

			w.Line("// <auto-generated />");
			w.Line("// Generated by Gtk4.Forms.MarkupCompiler — do not edit.");
			w.Line();

			if ((implicitBase != null && !isAppDef) || RegistersDictionary(root, classAttr, xamlPath, className)
				|| RegistersClassRoot(root, classAttr, xamlPath))
				EmitRegistration(w, xamlPath, className);
			if (!string.IsNullOrEmpty(ns))
			{
				w.Line($"namespace {ns} {{");
				w.Indent++;
			}

			w.Line(ClassDeclaration(typeName, implicitBase, rootBase));
			w.Indent++;

			// Collect named fields
			var namedElements = new List<(string fieldName, string fieldType)>();
			_fieldElements.Clear();
			_fieldNames.Clear();
			CollectNamedElements(root, xNs, namedElements);
			string rootName = RootNameField(root, xNs, typeName, namedElements);

			foreach (var (fieldName, fieldType) in namedElements)
				w.Line($"internal {fieldType} {fieldName};");

			w.Line("bool _contentLoaded;");
			w.Line();
			if (implicitBase != null || (rootBase != null && !isAppDef && NeedsGeneratedConstructor(root, className)))
			{
				w.Line($"public {typeName}() {{ InitializeComponent(); }}");
				w.Line();
			}

			// InitializeComponent
			w.Line("public void InitializeComponent() {");
			w.Indent++;
			w.Line("if (_contentLoaded) return;");
			w.Line("_contentLoaded = true;");
			if (rootName != null)
			{
				w.Line($"this.{rootName} = this;");
				EmitNameProperty(w, "this", ResolveType(root), rootName);
			}

			// WPF's XAML loader brackets the root with ISupportInitialize.BeginInit/EndInit, so
			// the root's Initialized fires (after its children's) before its constructor returns.
			// The (object) cast keeps the runtime check warning-free for any root type. A throwing body
			// abandons the root's init scope so it cannot hold back selection events thread-wide.
			if (!isAppDef)
			{
				w.Line(SupportInitializeCall("BeginInit"));
				w.Line("try");
				w.Line("{");
				w.Indent++;
			}

			// Emit root resources BEFORE attributes/children so {StaticResource} resolves.
			if (IsDictionaryRoot(root))
				EmitDictionaryRoot(w, root, xNs, ref _counter);
			else
			{
				EmitResources(w, root, xNs, "this", ref _counter);
				EmitRootAttributes(w, root, xNs);
				EmitChildren(w, root, xNs, "this", ref _counter);
			}

			if (!isAppDef)
			{
				w.Indent--;
				w.Line("}");
				w.Line("catch");
				w.Line("{");
				w.Indent++;
				w.Line("if ((object)this is global::System.Windows.FrameworkElement __initRoot)");
				w.Indent++;
				w.Line("global::System.Windows.FrameworkElement.AbandonInitialization(__initRoot);");
				w.Indent--;
				w.Line("throw;");
				w.Indent--;
				w.Line("}");
				w.Line(SupportInitializeCall("EndInit"));
			}

			w.Indent--;
			w.Line("}");

			// Application: also emit [STAThread] Main
			if (ShouldEmitMain(isAppDef, className))
			{
				w.Line();
				w.Line("[System.STAThread]");
				w.Line("static void Main() {");
				w.Indent++;
				w.Line($"var app = new {typeName}();");
				w.Line("app.InitializeComponent();");
				w.Line("app.Run();");
				w.Indent--;
				w.Line("}");
			}

			w.Indent--;
			w.Line("}");

			if (!string.IsNullOrEmpty(ns))
			{
				w.Indent--;
				w.Line("}");
			}

			return sb.ToString();
		}

		int _counter;

		// xmlns prefix→CLR namespace map, populated per-Generate call.
		Dictionary<string, string> _prefixMap = new Dictionary<string, string>(StringComparer.Ordinal);

		// Namespace URIs whose attributes/elements are stripped at compile time: the
		// markup-compatibility namespace itself plus every prefix listed in mc:Ignorable
		// (e.g. the d: design namespace). Populated per-document in Generate.
		HashSet<string> _ignorableNamespaces =
			new HashSet<string>(StringComparer.Ordinal) { WpfXmlnsMap.McNs };

		// ------------------------------------------------------------------ helpers

		/// <summary>
		/// Collects <c>xmlns:prefix="clr-namespace:Foo[;assembly=Bar]"</c> declarations
		/// from <paramref name="root"/> into a prefix→CLR-namespace dictionary.
		/// Only <c>clr-namespace:</c> URIs are stored; WPF presentation/x: namespaces are skipped.
		/// </summary>
		static Dictionary<string, string> CollectXmlnsPrefixMap(XElement root)
		{
			var map = new Dictionary<string, string>(StringComparer.Ordinal);
			foreach (XAttribute a in root.Attributes())
			{
				if (!a.IsNamespaceDeclaration) continue;
				// Namespace-declaration attributes have a.Name.LocalName == "prefix"
				// (or "xmlns" for the default namespace).
				string prefix = a.Name.LocalName;
				if (prefix == "xmlns") continue; // default namespace — no prefix

				string uri = a.Value ?? string.Empty;
				if (!uri.StartsWith("clr-namespace:", StringComparison.Ordinal)) continue;

				// Parse "clr-namespace:MyApp;assembly=MyApp" → "MyApp"
				string clrPart = uri.Substring("clr-namespace:".Length);
				int semi = clrPart.IndexOf(';');
				if (semi >= 0) clrPart = clrPart.Substring(0, semi);
				clrPart = clrPart.Trim();

				if (!string.IsNullOrEmpty(clrPart) && !map.ContainsKey(prefix))
					map[prefix] = clrPart;
			}
			return map;
		}

		static XNamespace GetXNamespace(XElement root)
		{
			// Prefer the 2009 URI; fall back to 2006.
			foreach (XAttribute a in root.Attributes())
			{
				if (a.IsNamespaceDeclaration)
				{
					if (a.Value == WpfXmlnsMap.XNs || a.Value == WpfXmlnsMap.XNs2006)
						return XNamespace.Get(a.Value);
				}
			}
			return XNamespace.Get(WpfXmlnsMap.XNs);
		}

		/// <summary>The root's <c>ISupportInitialize.<paramref name="method"/>()</c> call, when it implements it.</summary>
		internal static string SupportInitializeCall(string method) =>
			$"if ((object)this is System.ComponentModel.ISupportInitialize __init{method}) __init{method}.{method}();";

		/// <summary>
		/// Resolves an XAML element to its fully-qualified CLR type name.
		/// <para>
		/// Resolution order:
		/// <list type="number">
		/// <item>The built-in <see cref="WpfXmlnsMap"/> (fast path for all known WPF types).</item>
		/// <item>The xmlns-definition source injected via <see cref="SetXmlnsDefinitionSource"/>:
		///       each <c>(xmlnsUri, clrNamespace)</c> entry that matches the element's XML namespace
		///       is probed as <c>{clrNamespace}.{localName}</c>; when reference assemblies are
		///       available the probe is verified with a type-existence check so the correct namespace
		///       is chosen when the same local name appears in multiple CLR namespaces.</item>
		/// </list>
		/// </para>
		/// </summary>
		string ResolveType(XElement element)
		{
			string localName = element.Name.LocalName;
			string xmlNs = element.Name.NamespaceName;

			// Fast path: built-in presentation-namespace map covers all known WPF types.
			if (xmlNs == WpfXmlnsMap.PresentationNs)
			{
				string builtin = WpfXmlnsMap.Resolve(localName);
				if (builtin != null) return builtin;
			}

			// Xmlns-definition source: probe each matching CLR namespace in order.
			IReadOnlyList<XmlnsDefinitionEntry> entries = _xmlnsSource.GetEntries();
			for (int i = 0; i < entries.Count; i++)
			{
				XmlnsDefinitionEntry entry = entries[i];
				if (!string.Equals(entry.XmlNamespace, xmlNs, StringComparison.Ordinal)) continue;
				string candidate = entry.ClrNamespace + "." + localName;
				// When reference assemblies are loaded, verify the type actually exists in that
				// namespace before committing to it (avoids ambiguity when several CLR namespaces
				// map to the same xmlns URI, e.g. System.Windows and System.Windows.Controls).
				if (_resolver.TypeExists(candidate) || !_resolver.HasReferences)
					return candidate;
			}

			return null;
		}

		/// <summary>Emits root-element attribute assignments onto <c>this</c>.</summary>
		void EmitRootAttributes(IndentedWriter w, XElement root, XNamespace xNs)
		{
			string rootFqType = ResolveType(root) ?? string.Empty;

			foreach (XAttribute attr in root.Attributes())
			{
				if (attr.IsNamespaceDeclaration) continue;
				if (attr.Name.Namespace == xNs) continue; // x:Class etc.
				if (attr.Name.Namespace == XNamespace.Xml) continue; // xml:space/xml:lang directives
				if (IsIgnorableAttribute(attr)) continue;  // mc:Ignorable, d: design attrs

				string propName = attr.Name.LocalName;
				string val = attr.Value;
				int rootDot = propName.IndexOf('.');
				if (rootDot > 0 && !string.IsNullOrEmpty(rootFqType)
					&& ClassifyQualified(w, rootFqType, "this", propName.Substring(0, rootDot), ref propName, val)
						== Qualified.Emitted)
					continue;
				if (propName.IndexOf('.') > 0)
				{
					EmitRootAttached(w, "this", propName, val);
					continue;
				}

				if (IsKnownEvent(rootFqType, propName))
				{
					w.Line($"this.{propName} += this.{val};");
					continue;
				}

				if (IsTemplateBindingExpression(val, out string tbBindingInit))
				{
					string fqType = string.IsNullOrEmpty(rootFqType) ? "this" : rootFqType;
					w.Line($"this.SetBinding({fqType}.{propName}Property, {tbBindingInit});");
				}
				else if (IsBindingExpression(val, out string bindingInit))
				{
					string fqType = string.IsNullOrEmpty(rootFqType) ? "this" : rootFqType;
					w.Line($"this.SetBinding({fqType}.{propName}Property, {bindingInit});");
				}
				else if (IsDynamicResourceValue(val, out string dynKey) && !string.IsNullOrEmpty(rootFqType)
					&& IsKnownDp(rootFqType, propName))
					w.Line($"{Converter}.SetLocalResourceReference(this, {rootFqType}.{propName}Property, " +
						$"{ResourceKeyExpression(EscapeString(dynKey))});");
				else if (IsStaticOrDynamicResource(val, out string resourceKey))
				{
					// Style="{StaticResource k}" special-case; generic for other props.
					if (propName == "Style")
						w.Line($"this.Style = (System.Windows.Style)this.FindResource(" +
							$"{ResourceKeyExpression(EscapeString(resourceKey))});");
					else
					{
						string fqType = string.IsNullOrEmpty(rootFqType) ? "this" : rootFqType;
						w.Line($"this.SetValue({fqType}.{propName}Property, " +
							$"this.FindResource({ResourceKeyExpression(EscapeString(resourceKey))}));");
					}
				}
				else if (IsXNull(val))
				{
					if (!string.IsNullOrEmpty(rootFqType) && IsKnownDp(rootFqType, propName))
						w.Line($"this.SetValue({rootFqType}.{propName}Property, null);");
					else
						w.Line($"this.{propName} = {NullExprForClrProp(rootFqType, propName)};");
				}
				else if (IsXType(val, out string typeofExpr, _prefixMap, ProbePresentationType))
				{
					if (!string.IsNullOrEmpty(rootFqType) && IsKnownDp(rootFqType, propName))
						w.Line($"this.SetValue({rootFqType}.{propName}Property, {typeofExpr});");
					else
						w.Line($"this.{propName} = {typeofExpr};");
				}
				else if (IsXStatic(val, out string staticExpr, _prefixMap, ProbePresentationType))
				{
					if (!string.IsNullOrEmpty(rootFqType) && IsKnownDp(rootFqType, propName))
						w.Line($"this.SetValue({rootFqType}.{propName}Property, {staticExpr});");
					else
						w.Line($"this.{propName} = {staticExpr};");
				}
				else if (!string.IsNullOrEmpty(rootFqType) && IsKnownDp(rootFqType, propName))
				{
					w.Line($"this.SetValue({rootFqType}.{propName}Property, " +
						$"{DpValueExpression(rootFqType, propName, val)});");
				}
				else
				{
					w.Line($"this.{propName} = {ClrPropertyExpression(rootFqType, propName, val)};");
				}
			}
		}

		/// <summary>
		/// Returns the C# expression for a plain (non-binding, non-markup-extension)
		/// attribute value on a <see cref="DependencyProperty"/>.
		/// <para>
		/// For <c>StartupUri</c> emits <c>new System.Uri(...)</c>.
		/// For everything else defers to
		/// <c>System.Windows.Markup.XamlValueConverter.Convert(typeof(OwnerType), OwnerType.PropProperty, "raw")</c>
		/// so that runtime type-converter resolution handles Thickness, Brush, GridLength, etc.
		/// </para>
		/// </summary>
		static string DpValueExpression(string ownerType, string propName, string val)
		{
			if (propName == "StartupUri")
				return $"new System.Uri(\"{EscapeString(val)}\", System.UriKind.RelativeOrAbsolute)";

			return $"System.Windows.Markup.XamlValueConverter.Convert(" +
				$"typeof({ownerType}), {ownerType}.{propName}Property, \"{EscapeString(val)}\")";
		}

		/// <summary>
		/// The C# expression for a plain (non-binding) attribute value on a plain CLR property
		/// (non-DP path: Title, x:Name assignments, etc.).
		/// Phase-0 rules kept for backward compat (StartupUri, bool, numeric literals, string).
		/// </summary>
		static string ClrValueExpression(string propName, string val)
		{
			if (propName == "StartupUri")
				return $"new System.Uri(\"{EscapeString(val)}\", System.UriKind.RelativeOrAbsolute)";

			if (long.TryParse(val, System.Globalization.NumberStyles.Integer,
				System.Globalization.CultureInfo.InvariantCulture, out _))
				return val;

			if (double.TryParse(val, System.Globalization.NumberStyles.Float,
				System.Globalization.CultureInfo.InvariantCulture, out _)
				&& val.Contains("."))
				return val;

			if (string.Equals(val, "true", StringComparison.OrdinalIgnoreCase))
				return "true";
			if (string.Equals(val, "false", StringComparison.OrdinalIgnoreCase))
				return "false";

			return $"\"{EscapeString(val)}\"";
		}

		/// <summary>
		/// Returns the C# expression for <c>{x:Null}</c> on a plain CLR property.
		/// When the resolver can determine that <paramref name="propName"/> on
		/// <paramref name="ownerFqType"/> is a non-nullable value type, emits
		/// <c>default(T)</c>; otherwise emits <c>null</c>.
		/// </summary>
		string NullExprForClrProp(string ownerFqType, string propName)
		{
			if (!string.IsNullOrEmpty(ownerFqType))
			{
				Type propType = _resolver.GetPropertyType(ownerFqType, propName);
				if (propType != null && propType.IsValueType && Nullable.GetUnderlyingType(propType) == null)
					return $"default({propType.FullName})";
			}
			return "null";
		}

		/// <summary>
		/// Returns the C# cast-type name for the value parameter of an attached-property setter.
		/// Used when emitting <c>OwnerType.SetProp(el, (type)convert(...))</c>.
		/// Falls back to <c>object</c> for unknown combinations.
		/// </summary>
		string ResolveAttachedPropType(string ownerFqType, string propName)
		{
			string resolved = _resolver.GetAttachedSetterValueType(ownerFqType, propName);
			if (resolved != null) return resolved;
			// Grid attached props: Row, Column, RowSpan, ColumnSpan are int.
			if (ownerFqType == "System.Windows.Controls.Grid")
			{
				if (propName == "Row" || propName == "Column" ||
					propName == "RowSpan" || propName == "ColumnSpan")
					return "int";
			}
			// Canvas attached props: Left, Top, Right, Bottom are double.
			if (ownerFqType == "System.Windows.Controls.Canvas")
			{
				if (propName == "Left" || propName == "Top" ||
					propName == "Right" || propName == "Bottom")
					return "double";
			}
			// DockPanel attached prop: Dock is System.Windows.Controls.Dock enum.
			if (ownerFqType == "System.Windows.Controls.DockPanel" && propName == "Dock")
				return "System.Windows.Controls.Dock";
			// TextElement text properties (resolver-less generation, e.g. unit tests).
			if (ownerFqType == "System.Windows.Documents.TextElement")
			{
				switch (propName)
				{
					case "FontSize": return "double";
					case "Foreground": return "System.Windows.Media.Brush";
					case "FontFamily": return "System.Windows.Media.FontFamily";
					case "FontWeight": return "System.Windows.FontWeight";
					case "FontStyle": return "System.Windows.FontStyle";
					case "FontStretch": return "System.Windows.FontStretch";
				}
			}
			// Unknown: use object (a cast to object is a no-op; the setter will fail at runtime
			// if the type doesn't match, but code will compile).
			return "object";
		}

		/// <summary>
		/// Returns <c>true</c> for property names that are known WPF DependencyProperties
		/// on the given owner type (and therefore warrant the XamlValueConverter path).
		/// Properties like <c>Title</c>, <c>Content</c> that are plain CLR properties
		/// continue to use <see cref="ClrValueExpression"/>.
		/// <para>
		/// Phase-5 TODO: resolve this fully from the referenced assemblies' DP field names.
		/// For now, the convention "first letter upper-case + not in the CLR-only exclusion set"
		/// is used: any property with a matching <c>&lt;Name&gt;Property</c> field on the type
		/// will get the converter path; CLR-only props use the legacy path.
		/// </para>
		/// </summary>
		static readonly System.Collections.Generic.HashSet<string> _clrOnlyProperties =
			new System.Collections.Generic.HashSet<string>(StringComparer.Ordinal)
			{
				"Title", "StartupUri", "Name",
				// String DPs — XamlValueConverter would pass through anyway, but skip the overhead.
				"Text", "Header", "ToolTip",
				// object-typed DPs — string value is valid as-is; converter would pass through.
				"Content", "Tag", "DataContext", "CommandParameter",
			};

		/// <summary>
		/// Returns whether <paramref name="propName"/> should go through the DP converter
		/// path given owner <paramref name="fqType"/>.
		/// When reference paths were supplied, delegates to the assembly symbol resolver;
		/// otherwise falls back to the name heuristic (preserves existing test behaviour).
		/// </summary>
		bool IsKnownDp(string fqType, string propName)
		{
			// Always use CLR path for explicitly excluded properties.
			if (_clrOnlyProperties.Contains(propName)) return false;
			return _resolver.IsDP(fqType, propName) && _resolver.IsDependencyObject(fqType);
		}

		/// <summary>
		/// Returns whether <paramref name="propName"/> is a CLR event on <paramref name="fqType"/>,
		/// so a XAML <c>Event="Handler"</c> attribute is wired with <c>+= this.Handler</c> instead
		/// of being emitted as a property assignment.
		/// </summary>
		bool IsKnownEvent(string fqType, string propName)
		{
			if (string.IsNullOrEmpty(fqType)) return false;
			if (IsHookedUserType(fqType))
				return UserEventDeclared(propName) || UserBaseHasEvent(fqType, propName);
			return _resolver.IsEvent(fqType, propName);
		}

		/// <summary>
		/// Collects the namespace URIs to strip at compile time: the markup-compatibility
		/// namespace, plus every prefix listed in the root's <c>mc:Ignorable</c> (resolved to its
		/// declared URI, e.g. the <c>d:</c> Blend design namespace).
		/// </summary>
		static HashSet<string> CollectIgnorableNamespaces(XElement root)
		{
			var set = new HashSet<string>(StringComparer.Ordinal) { WpfXmlnsMap.McNs, PresentationOptionsNs };

			string ignorable = (string)root.Attribute(XNamespace.Get(WpfXmlnsMap.McNs) + "Ignorable");
			if (!string.IsNullOrWhiteSpace(ignorable))
			{
				foreach (string prefix in ignorable.Split(
					new[] { ' ', '\t', '\r', '\n' }, StringSplitOptions.RemoveEmptyEntries))
				{
					XNamespace ns = root.GetNamespaceOfPrefix(prefix);
					if (ns != null) set.Add(ns.NamespaceName);
				}
			}
			return set;
		}

		/// <summary>
		/// True for an attribute in a compile-time-ignored namespace, or a LocBaml <c>Localization.*</c> one.
		/// </summary>
		bool IsIgnorableAttribute(XAttribute attr) =>
			_ignorableNamespaces.Contains(attr.Name.Namespace.NamespaceName)
			|| attr.Name.LocalName == "Localization.Attributes" || attr.Name.LocalName == "Localization.Comments";

		/// <summary>
		/// Recursively emits construction + wiring for direct children of <paramref name="parentVar"/>.
		/// Regular children are constructed and attached; property-element children whose property
		/// is a known template property (<c>Template</c>, <c>ItemTemplate</c>, <c>ContentTemplate</c>)
		/// are emitted as template factories. All other property-element children are skipped
		/// (resources are handled by <see cref="EmitResources"/> before the element tree).
		/// </summary>
		void EmitChildren(
			IndentedWriter w,
			XElement parent,
			XNamespace xNs,
			string parentVar,
			ref int counter)
		{
			string parentLocalName = parent.Name.LocalName;
			ContentInfo ci = GetContentInfo(ResolveType(parent) ?? UserElementFqType(parent));
			bool inlines = ci != null && ci.IsCollection && ci.Name == "Inlines";

			List<object> content = CollectContent(parent, inlines);
			bool hasElements = content.Exists(IsContentElement);

			foreach (object item in content)
			{
				if (item is string text)
				{
					if (ci != null) EmitText(w, parentVar, ci, text, hasElements);
					continue;
				}
				XElement child = (XElement)item;
				if (!IsContentElement(child))
				{
					EmitPropertyElement(w, child, xNs, parentVar, ref counter);
					continue;
				}

				// x:Array element.
				if (TryEmitXArray(w, child, xNs, out string arrVar, ref counter))
				{
					EmitAttach(w, parentVar, parentLocalName, ci, arrVar, null);
					continue;
				}

				string fqType = ResolveType(child) ?? UserElementFqType(child);
				if (fqType == null)
				{
					if (IsMediaObjectType(ResolveType(parent)))
						NoteSkippedMedia(parent, "element " + child.Name.LocalName);
					continue;
				}

				string varName = $"__e{counter++}";
				string savedHook = _hookVar;
				_hookVar = IsHookedUserType(fqType) ? varName : _hookVar;
				EmitElement(w, child, xNs, varName, fqType, ref counter);
				_hookVar = savedHook;
				EmitAttach(w, parentVar, parentLocalName, ci, varName, fqType);
			}
		}

		/// <summary>
		/// Constructs and wires a single element into <paramref name="varName"/>.
		/// Used by both the page-body tree and template factory bodies.
		/// </summary>
		void EmitElement(
			IndentedWriter w,
			XElement el,
			XNamespace xNs,
			string varName,
			string fqType,
			ref int counter)
		{
			w.Line($"var {varName} = new {fqType}();");
			_scopeVars.Add(varName);

			// x:Name / Name field assignment
			string xName = NameOf(el, xNs);
			bool hasField = ResolveType(el) != null; // user-type resource objects get no field
			if (xName != null && _fieldElements.Contains(el))
			{
				w.Line($"this.{xName} = {varName};");
				EmitNameProperty(w, varName, fqType, xName);
				EmitNameRegistration(w, varName, xName);
			}

			// Emit <X.Resources> children first (before attr assignments that may reference them).
			EmitResources(w, el, xNs, varName, ref counter);

			// Attribute properties
			foreach (XAttribute attr in el.Attributes())
			{
				if (attr.IsNamespaceDeclaration) continue;
				if (attr.Name.Namespace == xNs) continue;
				if (attr.Name.Namespace == XNamespace.Xml) continue; // xml:space/xml:lang directives
				if (IsIgnorableAttribute(attr)) continue;  // mc:Ignorable, d: design attrs
				if (attr.Name.LocalName == "Name" && hasField && IsNamingAttribute(el, attr)) continue;

				string propName = attr.Name.LocalName;
				string val = attr.Value;
				if (SkippableMediaAttribute(el, fqType, attr))
				{
					NoteSkippedMedia(el, "attribute " + propName);
					continue;
				}
				if (SkipsUnknownMediaProperty(fqType, propName))
				{
					NoteSkippedMedia(el, "property " + propName);
					continue;
				}

				// Attached-property syntax: "Owner.Prop" (e.g. Grid.Row, Canvas.Left).
				int dotPos = propName.IndexOf('.');
				if (dotPos > 0)
				{
					string owner = propName.Substring(0, dotPos);
					Qualified q = ClassifyQualified(w, fqType, varName, owner, ref propName, val);
					if (q == Qualified.Emitted) continue;
					if (q == Qualified.OwnMember) dotPos = -1;
				}
				if (dotPos > 0)
				{
					string ownerLocalName = propName.Substring(0, dotPos);
					string attachedProp = propName.Substring(dotPos + 1);
					string ownerFqType = QualifyTypeName(ownerLocalName);
					// Emit: OwnerType.SetProp(element, (castType)XamlValueConverter.Convert(...))
					string castType = ResolveAttachedPropType(ownerFqType, attachedProp);
					string ownerEmit = Emitted(ownerFqType);
					if (IsTemplateBindingExpression(val, out string attachedTb) || IsBindingExpression(val, out attachedTb))
					{
						w.Line(SetBindingLine(varName, fqType, $"{ownerEmit}.{attachedProp}Property", attachedTb));
						continue;
					}
					w.Line($"{ownerEmit}.Set{attachedProp}({varName}, " +
						$"({castType})System.Windows.Markup.XamlValueConverter.Convert(" +
						$"typeof({ownerEmit}), {ownerEmit}.{attachedProp}Property, \"{EscapeString(val)}\"));");
					continue;
				}

				// CLR event: Click="Handler" → element.Click += this.Handler;
				if (IsKnownEvent(fqType, propName))
				{
					w.Line($"{varName}.{propName} += this.{val};");
					continue;
				}

				string hookFind = IsStaticResourceValue(val, out string hookKey)
					? StaticResourceLookup(varName, EscapeString(hookKey)) : null;
				if (varName == _hookVar && TryEmitDefinitionShorthand(w, fqType, varName, propName, val)) continue;
				if (TryEmitHookProperty(w, varName, propName, val, hookFind)) continue;

				if (IsTemplateBindingExpression(val, out string tbBindingInit))
					w.Line(SetBindingLine(varName, fqType, $"{fqType}.{propName}Property", tbBindingInit));
				else if (IsBindingExpression(val, out string bindingInit))
					w.Line(SetBindingLine(varName, fqType, $"{fqType}.{propName}Property", bindingInit));
				else if (MediaResourceTarget(fqType, propName, val) is Type mediaType
					&& IsStaticOrDynamicResource(val, out string mediaKey))
					w.Line(varName + "." + propName + " = " + (val.TrimStart().StartsWith("{StaticResource",
						StringComparison.Ordinal) ? StaticResourceLookup("this", EscapeString(mediaKey))
						: DynamicMediaLookup(EscapeString(mediaKey)))
						+ " as global::" + mediaType.FullName.Replace('+', '.') + ";");
				else if (IsDynamicResourceValue(val, out string freezableKey) && IsKnownDp(fqType, propName)
					&& IsNonElementDependencyObject(fqType))
					w.Line($"{Converter}.SetResourceValue(this, {varName}, {fqType}.{propName}Property, " +
						$"{ResourceKeyExpression(EscapeString(freezableKey))}{ResourceScopeArgs(varName)});");
				else if (IsDynamicResourceValue(val, out string dynKey) && IsKnownDp(fqType, propName))
					w.Line($"{Converter}.SetLocalResourceReference({varName}, {fqType}.{propName}Property, " +
						$"{ResourceKeyExpression(EscapeString(dynKey))});");
				else if (varName == _hookVar && IsDynamicResourceValue(val, out string hookDynKey))
					w.Line($"if ((object){varName} is global::System.Windows.FrameworkElement) " +
						$"{Converter}.SetLocalResourceReference((global::System.Windows.FrameworkElement)(object)" +
						$"{varName}, " +
						$"{fqType}.{propName}Property, " +
						$"{ResourceKeyExpression(EscapeString(hookDynKey))});");
				else if (IsStaticOrDynamicResource(val, out string resourceKey))
				{
					string find = val.TrimStart().StartsWith("{StaticResource", StringComparison.Ordinal)
						? StaticResourceLookup(varName, EscapeString(resourceKey))
						: $"{varName}.FindResource({ResourceKeyExpression(EscapeString(resourceKey))})";
					string clrType = hookFind != null ? ClrResourceTargetType(fqType, propName) : null;
					if (propName == "Style")
						w.Line($"{varName}.Style = (System.Windows.Style){find};");
					else if (clrType != null)
						w.Line($"{varName}.{propName} = ({clrType})System.Windows.Markup.XamlValueConverter" +
							$".CoerceResource(typeof({clrType}), {find});");
					else
						w.Line($"{varName}.SetValue({fqType}.{propName}Property, " +
							$"{(IsNonElementDependencyObject(fqType) ? CoercedDpValue(fqType, propName, find) : find)});");
				}
				else if (TryEmitDefinitionShorthand(w, fqType, varName, propName, val)) { }
				else if (TryPrefixedCommand(fqType, propName, val, out string commandExpr))
				{
					w.Line(IsKnownDp(fqType, propName)
						? $"{varName}.SetValue({fqType}.{propName}Property, {commandExpr});"
						: $"{varName}.{propName} = {commandExpr};");
				}
				else if (IsXNull(val))
				{
					if (IsKnownDp(fqType, propName))
						w.Line($"{varName}.SetValue({fqType}.{propName}Property, null);");
					else
						w.Line($"{varName}.{propName} = {NullExprForClrProp(fqType, propName)};");
				}
				else if (IsXType(val, out string typeofExpr, _prefixMap, ProbePresentationType))
				{
					if (IsKnownDp(fqType, propName))
						w.Line($"{varName}.SetValue({fqType}.{propName}Property, {typeofExpr});");
					else
						w.Line($"{varName}.{propName} = {typeofExpr};");
				}
				else if (IsXStatic(val, out string staticExpr, _prefixMap, ProbePresentationType))
				{
					if (IsKnownDp(fqType, propName))
						w.Line($"{varName}.SetValue({fqType}.{propName}Property, {staticExpr});");
					else
						w.Line($"{varName}.{propName} = {staticExpr};");
				}
				else if (IsKnownDp(fqType, propName))
				{
					w.Line($"{varName}.SetValue({fqType}.{propName}Property, " +
						$"{DpValueExpression(fqType, propName, val)});");
				}
				else
					w.Line($"{varName}.{propName} = {ClrPropertyExpression(fqType, propName, val)};");
			}

			// Recurse into grandchildren (passes varName as parentVar — single-child or Children.Add)
			EmitChildren(w, el, xNs, varName, ref counter);
			_scopeVars.RemoveAt(_scopeVars.Count - 1);
		}

		/// <summary>
		/// Handles property-element children whose property name contains a dot
		/// (e.g. <c>&lt;Button.Template&gt;</c>, <c>&lt;ListBox.ItemTemplate&gt;</c>,
		/// <c>&lt;VisualStateManager.VisualStateGroups&gt;</c>,
		/// <c>&lt;Button.Triggers&gt;</c> / <c>&lt;FrameworkElement.Triggers&gt;</c>).
		/// Only template-typed properties, VSM groups, and Triggers blocks are emitted;
		/// everything else is skipped.
		/// </summary>
		void EmitPropertyElement(
			IndentedWriter w,
			XElement propEl,
			XNamespace xNs,
			string parentVar,
			ref int counter)
		{
			string localName = propEl.Name.LocalName;
			int dot = localName.IndexOf('.');
			if (dot < 0) return;

			// Provider parameter lists are emitted with the provider (EmitProviderParameters).
			if (IsParameterList(propEl)) return;

			string propName = localName.Substring(dot + 1);

			// Resources blocks are owned by EmitResources; skip here to avoid
			// a bogus {owner}.Resources = {tmplVar} assignment (CS0200) and
			// re-emitting only the first template child.
			if (propName == "Resources") return;

			// VisualStateManager.VisualStateGroups attached-property form.
			string ownerLocalName = localName.Substring(0, dot);
			if (ownerLocalName == "VisualStateManager" && propName == "VisualStateGroups")
			{
				EmitVisualStateGroups(w, propEl, xNs, parentVar, ref counter);
				return;
			}

			if (TryEmitSweep4PropertyElement(w, propEl, xNs, parentVar, propName, ref counter)) return;
			if (TryEmitMediaPropertyElement(w, propEl, xNs, parentVar, propName, ref counter)) return;

			if (TryEmitItemCollection(w, propEl, xNs, parentVar, QualifyTypeName(ownerLocalName), propName,
				ref counter)) return;

			// {AnyElement}.Triggers — element-level trigger block.
			if (propName == "Triggers")
			{
				EmitElementTriggers(w, propEl, xNs, parentVar, ref counter);
				return;
			}

			if (TryEmitAttachedPropertyElement(w, propEl, xNs, parentVar, ownerLocalName, propName, ref counter))
				return;

			// Template and ContentTemplate property elements contain a ControlTemplate child.
			// ItemTemplate property elements contain a DataTemplate child.
			// MultiBinding property elements contain a MultiBinding child.
			string ownerFqType = AttachedOwnerType(propEl, ownerLocalName);

			foreach (XElement child in propEl.Elements())
			{
				string childLocal = child.Name.LocalName;
				if (childLocal == "Binding")
				{
					string bVar = $"__b{counter++}";
					EmitBindingElementInline(w, child, bVar, ref counter);
					w.Line(SetBindingLine(parentVar, ParentFqType(propEl), $"{ownerFqType}.{propName}Property", bVar));
					return;
				}
				if (childLocal == "BindingGroup" && (propName == "BindingGroup" || propName == "ItemBindingGroup"))
				{
					EmitBindingGroupElement(w, child, parentVar, propName, ref counter);
					return;
				}
				if (childLocal == "ControlTemplate")
				{
					string tmplVar = $"__ct{counter++}";
					EmitControlTemplateInline(w, child, xNs, tmplVar, ref counter);
					w.Line($"{parentVar}.{propName} = {tmplVar};");
					return;
				}
				if (childLocal == "DataTemplate")
				{
					string tmplVar = $"__dt{counter++}";
					EmitDataTemplateInline(w, child, xNs, tmplVar, ref counter);
					w.Line($"{parentVar}.{propName} = {tmplVar};");
					return;
				}
				if (childLocal == "HierarchicalDataTemplate")
				{
					string tmplVar = $"__dt{counter++}";
					EmitHierarchicalTemplateInline(w, child, xNs, tmplVar, parentVar, ref counter);
					w.Line($"{parentVar}.{propName} = {tmplVar};");
					return;
				}
				if (childLocal == "MultiBinding")
				{
					string mbVar = $"__mb{counter++}";
					EmitMultiBindingInline(w, child, xNs, mbVar, ref counter);
					// SetBinding(DP, BindingBase): resolve DP from owner type name.
					w.Line(SetBindingLine(parentVar, ParentFqType(propEl), $"{ownerFqType}.{propName}Property", mbVar));
					return;
				}
			}
			if (TryEmitElementMediaProperty(w, propEl, xNs, parentVar, propName, ref counter)) return;
			if (TryEmitObjectPropertyElement(w, propEl, xNs, parentVar, propName, ref counter)) return;
			if (TryEmitTextPropertyElement(w, propEl, parentVar, propName)) return;
			if (!_ignorableNamespaces.Contains(propEl.Name.NamespaceName)) NoteDroppedPropertyElement(propEl);
		}

		/// <summary>
		/// Emits code to populate <paramref name="ownerVar"/>.Resources from a
		/// <c>&lt;Owner.Resources&gt;</c> property element (if present on <paramref name="element"/>).
		/// Supports <c>&lt;Style x:Key="k" TargetType="T"&gt;&lt;Setter…/&gt;&lt;/Style&gt;</c>
		/// and simple keyed values.
		/// </summary>
		void EmitResources(
			IndentedWriter w,
			XElement element,
			XNamespace xNs,
			string ownerVar,
			ref int counter)
		{
			string localName = element.Name.LocalName;

			// Find <LocalName.Resources> property element.
			XElement resPropEl = null;
			foreach (XElement ch in element.Elements())
			{
				if (ch.Name.LocalName == localName + ".Resources")
				{ resPropEl = ch; break; }
			}
			if (resPropEl == null) return;

			// The direct child may be a <ResourceDictionary> wrapper or the items directly.
			// Collect the actual resource items.
			System.Collections.Generic.IEnumerable<XElement> items;
			XElement rdWrapper = null;
			foreach (XElement ch in resPropEl.Elements())
			{
				if (ch.Name.LocalName == "ResourceDictionary"
					&& ch.Name.NamespaceName == WpfXmlnsMap.PresentationNs)
				{ rdWrapper = ch; break; }
			}
			items = rdWrapper != null ? rdWrapper.Elements() : resPropEl.Elements();
			if (rdWrapper != null) EmitDictionarySource(w, rdWrapper, ownerVar);
			EmitResourceItems(w, items, xNs, ownerVar, ref counter);
		}

		/// <summary>
		/// Emits a local variable <paramref name="tmplVar"/> of type
		/// <see cref="System.Windows.Controls.ControlTemplate"/> whose <c>Factory</c>
		/// builds the single visual-root child of <paramref name="tmplEl"/>.
		/// <para>
		/// The factory is a lambda <c>() =&gt; { var __e0 = …; return __e0; }</c> that
		/// uses the same element-construction codegen as the page body.
		/// </para>
		/// </summary>
		void EmitControlTemplateInline(
			IndentedWriter w,
			XElement tmplEl,
			XNamespace xNs,
			string tmplVar,
			ref int counter)
		{
			string targetTypeAttr = (string)tmplEl.Attribute("TargetType");
			string targetTypeExpr = TypeRefExpression(targetTypeAttr);

			w.Line($"var {tmplVar} = new System.Windows.Controls.ControlTemplate({targetTypeExpr});");

			// Find the single visual root inside the ControlTemplate.
			XElement root = FindTemplateRoot(tmplEl);
			if (root != null)
			{
				string rootFqType = ResolveType(root);
				if (rootFqType != null)
				{
					string rootVar = $"__e{counter++}";
					w.Line($"{tmplVar}.Factory = () => {{");
					w.Indent++;
					EmitElement(w, root, xNs, rootVar, rootFqType, ref counter);
					w.Line($"return {rootVar};");
					w.Indent--;
					w.Line("};");
				}
			}
		}

		/// <summary>
		/// Emits a local variable <paramref name="tmplVar"/> of type
		/// <see cref="System.Windows.Controls.DataTemplate"/> whose <c>ItemFactory</c>
		/// builds the single visual-root child, with <c>__item</c> as the data context.
		/// Any <c>{Binding}</c> expressions inside bind against <c>__item</c>'s DataContext.
		/// </summary>
		void EmitDataTemplateInline(
			IndentedWriter w,
			XElement tmplEl,
			XNamespace xNs,
			string tmplVar,
			ref int counter,
			string typeName = "System.Windows.Controls.DataTemplate")
		{
			w.Line($"var {tmplVar} = new {typeName}();");
			string dataType = DataTypeExpression((string)tmplEl.Attribute("DataType"));
			if (dataType != "null") w.Line($"{tmplVar}.DataType = {dataType};");

			XElement root = FindTemplateRoot(tmplEl);
			if (root != null)
			{
				string rootFqType = ResolveType(root);
				if (rootFqType != null)
				{
					string rootVar = $"__e{counter++}";
					w.Line($"{tmplVar}.ItemFactory = __item => {{");
					w.Indent++;
					EmitElement(w, root, xNs, rootVar, rootFqType, ref counter);
					// Set DataContext so bindings inside the template pick up the item.
					w.Line($"if ({rootVar} is System.Windows.FrameworkElement __fe{counter}) __fe{counter++}.DataContext = __item;");
					w.Line($"return {rootVar};");
					w.Indent--;
					w.Line("};");
				}
			}
		}

		/// <summary>
		/// Returns the first non-property-element child of a template element (the visual root).
		/// </summary>
		static XElement FindTemplateRoot(XElement tmplEl)
		{
			foreach (XElement ch in tmplEl.Elements())
			{
				if (ch.Name.LocalName.IndexOf('.') < 0
					&& ch.Name.NamespaceName == WpfXmlnsMap.PresentationNs)
					return ch;
			}
			return null;
		}

		/// <summary>
		/// Emits code that constructs a <see cref="System.Windows.Style"/> from a
		/// <c>&lt;Style TargetType="T"&gt;</c> element and returns the local holding it;
		/// <see cref="EmitStyleResource"/> files it under its key.
		/// </summary>
		string EmitStyleObject(
			IndentedWriter w,
			XElement styleEl,
			XNamespace xNs,
			string ownerVar,
			ref int counter)
		{
			string styleVar = $"__style{counter++}";

			// TargetType attribute.
			string targetTypeAttr = (string)styleEl.Attribute("TargetType");
			string targetTypeExpr = TypeRefExpression(targetTypeAttr);

			// BasedOn="{StaticResource k}" attribute.
			string basedOnAttr = (string)styleEl.Attribute("BasedOn");
			string basedOnKey = null;
			if (basedOnAttr != null && IsStaticOrDynamicResource(basedOnAttr, out string bk))
				basedOnKey = bk;

			w.Line($"var {styleVar} = new System.Windows.Style({targetTypeExpr});");
			if (basedOnKey != null)
				w.Line($"{styleVar}.BasedOn = (System.Windows.Style){BasedOnLookup(ownerVar, basedOnKey)};");

			// Setter children.
			foreach (XElement ch in styleEl.Elements())
			{
				if (ch.Name.LocalName == "Setter")
				{
					string propAttr = (string)ch.Attribute("Property");
					if (propAttr == null) continue;
					string escapedProp = EscapeString(propAttr);
					string valExpr = SetterValueExpression(w, ch, ownerVar);
					w.Line($"{styleVar}.Setters.Add(new System.Windows.Setter {{ PropertyName = \"{escapedProp}\", Value = {valExpr} }});");
				}
				else if (ch.Name.LocalName == "EventSetter")
				{
					EmitEventSetter(w, ch, $"{styleVar}.Setters", targetTypeAttr);
				}
				else if (ch.Name.LocalName == "Style.Triggers")
				{
					EmitStyleTriggers(w, ch, xNs, styleVar, ownerVar, ref counter);
				}
			}

			return styleVar;
		}

		/// <summary>
		/// Emits code for all trigger elements inside a <c>&lt;Style.Triggers&gt;</c>
		/// property element, calling <c>styleVar.Triggers.Add(…)</c> for each.
		/// Handles: Trigger, DataTrigger, MultiTrigger, EventTrigger.
		/// </summary>
		void EmitStyleTriggers(
			IndentedWriter w,
			XElement triggersEl,
			XNamespace xNs,
			string styleVar,
			string receiver,
			ref int counter)
		{
			foreach (XElement ch in triggersEl.Elements())
			{
				string trigVar = $"__t{counter++}";
				switch (ch.Name.LocalName)
				{
					case "Trigger":
						EmitTriggerToCollection(w, ch, trigVar, styleVar, receiver);
						break;
					case "DataTrigger":
						EmitDataTriggerToCollection(w, ch, trigVar, styleVar, receiver);
						break;
					case "MultiTrigger":
						EmitMultiTriggerToCollection(w, ch, xNs, trigVar, styleVar, receiver, ref counter);
						break;
					case "EventTrigger":
						EmitEventTrigger(w, ch, xNs, trigVar, styleVar, ref counter);
						break;
				}
			}
		}

		/// <summary>
		/// Emits a <see cref="System.Windows.Trigger"/> and adds it to
		/// <paramref name="containerVar"/>.Triggers.
		/// Used by both <c>Style.Triggers</c> and element-level trigger blocks.
		/// </summary>
		void EmitTriggerToCollection(
			IndentedWriter w, XElement el, string trigVar, string containerVar, string receiver)
		{
			string propAttr = (string)el.Attribute("Property") ?? string.Empty;
			string valAttr = (string)el.Attribute("Value") ?? string.Empty;
			w.Line($"var {trigVar} = new System.Windows.Trigger {{ " +
				$"PropertyName = \"{EscapeString(propAttr)}\", Value = \"{EscapeString(valAttr)}\" }};");
			foreach (XElement setter in el.Elements())
			{
				if (setter.Name.LocalName != "Setter") continue;
				string p = (string)setter.Attribute("Property") ?? string.Empty;
				string vExpr = SetterValueExpression(w, setter, receiver);
				w.Line($"{trigVar}.Setters.Add(new System.Windows.Setter {{ PropertyName = \"{EscapeString(p)}\", Value = {vExpr} }});");
			}
			w.Line($"{containerVar}.Triggers.Add({trigVar});");
		}

		/// <summary>
		/// Emits a <see cref="System.Windows.DataTrigger"/> and adds it to
		/// <paramref name="containerVar"/>.Triggers.
		/// Used by both <c>Style.Triggers</c> and element-level trigger blocks.
		/// </summary>
		void EmitDataTriggerToCollection(
			IndentedWriter w, XElement el, string trigVar, string containerVar, string receiver)
		{
			string bindingAttr = (string)el.Attribute("Binding") ?? string.Empty;
			string valAttr = (string)el.Attribute("Value") ?? string.Empty;
			string bindingExpr = "null";
			if (IsBindingExpression(bindingAttr, out string bInit))
				bindingExpr = bInit;
			w.Line($"var {trigVar} = new System.Windows.DataTrigger {{ Binding = {bindingExpr}, Value = \"{EscapeString(valAttr)}\" }};");
			foreach (XElement setter in el.Elements())
			{
				if (setter.Name.LocalName != "Setter") continue;
				string p = (string)setter.Attribute("Property") ?? string.Empty;
				string vExpr = SetterValueExpression(w, setter, receiver);
				w.Line($"{trigVar}.Setters.Add(new System.Windows.Setter {{ PropertyName = \"{EscapeString(p)}\", Value = {vExpr} }});");
			}
			w.Line($"{containerVar}.Triggers.Add({trigVar});");
		}

		/// <summary>
		/// Emits a <see cref="System.Windows.MultiTrigger"/> and adds it to
		/// <paramref name="containerVar"/>.Triggers.
		/// Used by both <c>Style.Triggers</c> and element-level trigger blocks.
		/// </summary>
		void EmitMultiTriggerToCollection(
			IndentedWriter w,
			XElement el,
			XNamespace xNs,
			string trigVar,
			string containerVar,
			string receiver,
			ref int counter)
		{
			w.Line($"var {trigVar} = new System.Windows.MultiTrigger();");
			foreach (XElement child in el.Elements())
			{
				if (child.Name.LocalName == "MultiTrigger.Conditions")
				{
					foreach (XElement cond in child.Elements())
					{
						if (cond.Name.LocalName != "Condition") continue;
						string p = (string)cond.Attribute("Property") ?? string.Empty;
						string v = (string)cond.Attribute("Value") ?? string.Empty;
						w.Line($"{trigVar}.Conditions.Add(new System.Windows.Condition {{ " +
							$"PropertyName = \"{EscapeString(p)}\", Value = \"{EscapeString(v)}\" }});");
					}
				}
				else if (child.Name.LocalName == "Setter")
				{
					string p = (string)child.Attribute("Property") ?? string.Empty;
					string vExpr = SetterValueExpression(w, child, receiver);
					w.Line($"{trigVar}.Setters.Add(new System.Windows.Setter {{ " +
						$"PropertyName = \"{EscapeString(p)}\", Value = {vExpr} }});");
				}
			}
			w.Line($"{containerVar}.Triggers.Add({trigVar});");
		}

		void EmitEventTrigger(
			IndentedWriter w,
			XElement el,
			XNamespace xNs,
			string trigVar,
			string containerVar,
			ref int counter)
		{
			EmitEventTriggerFull(w, el, xNs, trigVar, containerVar, true, ref counter);
		}

