using System;
using System.Collections.Generic;
using System.IO;
using System.Text;
using System.Xml;
using System.Xml.Linq;

namespace Gtk.Forms.MarkupCompiler
{
	/// <summary>
	/// Pure, unit-testable core: parses a WPF XAML document and emits the
	/// <c>InitializeComponent</c> partial class (C# source text).
	/// No MSBuild, no System.Xaml dependency.
	/// </summary>
	public class XamlCodeGenerator
	{
		/// <summary>
		/// Generates the <c>.g.cs</c> source for <paramref name="xaml"/>.
		/// </summary>
		/// <param name="xaml">Raw XAML text.</param>
		/// <param name="className">
		/// Receives the fully-qualified class name (e.g. <c>MyApp.MainWindow</c>), or
		/// <c>null</c> when <c>x:Class</c> is absent.
		/// </param>
		/// <returns>Generated C# source text, or <c>null</c> when nothing should be emitted.</returns>
		public string Generate(string xaml, out string className)
		{
			if (xaml == null) throw new ArgumentNullException(nameof(xaml));

			XDocument doc;
			try
			{
				doc = XDocument.Parse(xaml, LoadOptions.PreserveWhitespace);
			}
			catch (XmlException ex)
			{
				throw new XamlCodeGeneratorException("XAML parse error: " + ex.Message, ex);
			}

			XElement root = doc.Root;
			if (root == null)
			{
				className = null;
				return null;
			}

			XNamespace xNs = GetXNamespace(root);
			XAttribute classAttr = root.Attribute(xNs + "Class");
			if (classAttr == null)
			{
				className = null;
				return null;
			}

			className = classAttr.Value.Trim();
			int lastDot = className.LastIndexOf('.');
			string ns = lastDot >= 0 ? className.Substring(0, lastDot) : string.Empty;
			string typeName = lastDot >= 0 ? className.Substring(lastDot + 1) : className;

			bool isAppDef = IsApplicationDefinition(root);

			var sb = new StringBuilder();
			var w = new IndentedWriter(sb);

			w.Line("// <auto-generated />");
			w.Line("// Generated by Gtk.Forms.MarkupCompiler — do not edit.");
			w.Line();

			if (!string.IsNullOrEmpty(ns))
			{
				w.Line($"namespace {ns} {{");
				w.Indent++;
			}

			w.Line($"public partial class {typeName} {{");
			w.Indent++;

			// Collect named fields
			var namedElements = new List<(string fieldName, string fieldType)>();
			CollectNamedElements(root, xNs, namedElements);

			foreach (var (fieldName, fieldType) in namedElements)
				w.Line($"internal {fieldType} {fieldName};");

			w.Line("bool _contentLoaded;");
			w.Line();

			// InitializeComponent
			w.Line("public void InitializeComponent() {");
			w.Indent++;
			w.Line("if (_contentLoaded) return;");
			w.Line("_contentLoaded = true;");

			EmitRootAttributes(w, root, xNs);
			EmitChildren(w, root, xNs, "this", ref _counter);

			w.Indent--;
			w.Line("}");

			// Application: also emit [STAThread] Main
			if (isAppDef)
			{
				w.Line();
				w.Line("[System.STAThread]");
				w.Line("static void Main() {");
				w.Indent++;
				w.Line($"var app = new {typeName}();");
				w.Line("app.InitializeComponent();");
				w.Line("app.Run();");
				w.Indent--;
				w.Line("}");
			}

			w.Indent--;
			w.Line("}");

			if (!string.IsNullOrEmpty(ns))
			{
				w.Indent--;
				w.Line("}");
			}

			return sb.ToString();
		}

		int _counter;

		// ------------------------------------------------------------------ helpers

		static XNamespace GetXNamespace(XElement root)
		{
			// Prefer the 2009 URI; fall back to 2006.
			foreach (XAttribute a in root.Attributes())
			{
				if (a.IsNamespaceDeclaration)
				{
					if (a.Value == WpfXmlnsMap.XNs || a.Value == WpfXmlnsMap.XNs2006)
						return XNamespace.Get(a.Value);
				}
			}
			return XNamespace.Get(WpfXmlnsMap.XNs);
		}

		static bool IsApplicationDefinition(XElement root)
		{
			return root.Name.LocalName == "Application";
		}

		static string ResolveType(XElement element)
		{
			string localName = element.Name.LocalName;
			string ns = element.Name.NamespaceName;
			if (ns == WpfXmlnsMap.PresentationNs)
				return WpfXmlnsMap.Resolve(localName);
			return null;
		}

		/// <summary>Collects all elements that carry <c>x:Name</c> or <c>Name</c>.</summary>
		static void CollectNamedElements(
			XElement parent,
			XNamespace xNs,
			List<(string, string)> results)
		{
			foreach (XElement child in parent.Elements())
			{
				string name = (string)(child.Attribute(xNs + "Name") ?? child.Attribute("Name"));
				if (name != null)
				{
					string fqType = ResolveType(child);
					if (fqType != null)
						results.Add((name, fqType));
				}
				CollectNamedElements(child, xNs, results);
			}
		}

		/// <summary>Emits root-element attribute assignments onto <c>this</c>.</summary>
		static void EmitRootAttributes(IndentedWriter w, XElement root, XNamespace xNs)
		{
			foreach (XAttribute attr in root.Attributes())
			{
				if (attr.IsNamespaceDeclaration) continue;
				if (attr.Name.Namespace == xNs) continue; // x:Class etc.

				string propName = attr.Name.LocalName;
				string val = attr.Value;

				if (IsBindingExpression(val, out string bindingPath))
				{
					string fqType = ResolveType(root) ?? "this";
					w.Line($"this.SetBinding({fqType}.{propName}Property, new System.Windows.Data.Binding(\"{bindingPath}\"));");
				}
				else
				{
					w.Line($"this.{propName} = {ValueExpression(propName, val)};");
				}
			}
		}

		/// <summary>
		/// The C# expression for a plain (non-binding) attribute value. Phase 0 emits a string literal
		/// except for the few known typed WPF properties (Application.StartupUri is a System.Uri); later
		/// phases resolve the target property type (and its type converter) from the referenced assemblies.
		/// </summary>
		static string ValueExpression(string propName, string val)
		{
			if (propName == "StartupUri")
				return $"new System.Uri(\"{EscapeString(val)}\", System.UriKind.RelativeOrAbsolute)";
			return $"\"{EscapeString(val)}\"";
		}

		/// <summary>
		/// Recursively emits construction + wiring for direct children of <paramref name="parentVar"/>.
		/// </summary>
		void EmitChildren(
			IndentedWriter w,
			XElement parent,
			XNamespace xNs,
			string parentVar,
			ref int counter)
		{
			string parentLocalName = parent.Name.LocalName;

			foreach (XElement child in parent.Elements())
			{
				string fqType = ResolveType(child);
				if (fqType == null) continue;

				string varName = $"__e{counter++}";
				w.Line($"var {varName} = new {fqType}();");

				// x:Name / Name field assignment
				string xName = (string)(child.Attribute(xNs + "Name") ?? child.Attribute("Name"));
				if (xName != null)
					w.Line($"this.{xName} = {varName};");

				// Attribute properties
				foreach (XAttribute attr in child.Attributes())
				{
					if (attr.IsNamespaceDeclaration) continue;
					if (attr.Name.Namespace == xNs) continue;
					if (attr.Name.LocalName == "Name") continue;

					string propName = attr.Name.LocalName;
					string val = attr.Value;

					if (IsBindingExpression(val, out string bindingPath))
						w.Line($"{varName}.SetBinding({fqType}.{propName}Property, new System.Windows.Data.Binding(\"{bindingPath}\"));");
					else
						w.Line($"{varName}.{propName} = {ValueExpression(propName, val)};");
				}

				// Recurse into grandchildren
				EmitChildren(w, child, xNs, varName, ref counter);

				// Attach child to parent
				if (WpfXmlnsMap.HasChildren(parentLocalName))
					w.Line($"{parentVar}.Children.Add({varName});");
				else
					w.Line($"{parentVar}.Content = {varName};");
			}
		}

		static bool IsBindingExpression(string value, out string path)
		{
			path = null;
			if (value == null) return false;
			string trimmed = value.Trim();
			if (!trimmed.StartsWith("{Binding", StringComparison.Ordinal)) return false;
			if (!trimmed.EndsWith("}")) return false;

			// {Binding} or {Binding Path} or {Binding Path=X}
			string inner = trimmed.Substring("{Binding".Length).TrimEnd('}').Trim();
			if (string.IsNullOrEmpty(inner))
			{
				path = string.Empty;
				return true;
			}

			// Handle "Path=X" or positional path
			if (inner.StartsWith("Path=", StringComparison.Ordinal))
				path = inner.Substring("Path=".Length).Trim();
			else
				path = inner;

			return true;
		}

		static string EscapeString(string s) => s.Replace("\\", "\\\\").Replace("\"", "\\\"");
	}

	/// <summary>Exception thrown when XAML code generation fails.</summary>
	public class XamlCodeGeneratorException : Exception
	{
		/// <inheritdoc />
		public XamlCodeGeneratorException(string message) : base(message) { }

		/// <inheritdoc />
		public XamlCodeGeneratorException(string message, Exception inner) : base(message, inner) { }
	}

	/// <summary>Simple indenting writer over a <see cref="StringBuilder"/>.</summary>
	sealed class IndentedWriter
	{
		readonly StringBuilder _sb;
		int _indent;
		const string Tab = "\t";

		internal IndentedWriter(StringBuilder sb) { _sb = sb; }

		internal int Indent
		{
			get => _indent;
			set => _indent = value < 0 ? 0 : value;
		}

		internal void Line(string text = "")
		{
			if (string.IsNullOrEmpty(text))
			{
				_sb.AppendLine();
				return;
			}
			for (int i = 0; i < _indent; i++) _sb.Append(Tab);
			_sb.AppendLine(text);
		}
	}
}
