namespace System.Windows;

/// <summary>
/// Standard clipboard/data-transfer format name constants, matching the WPF API.
/// </summary>
public static class DataFormats
{
	/// <summary>Specifies the ANSI text format.</summary>
	public const string Text = "Text";

	/// <summary>Specifies the Unicode text format.</summary>
	public const string UnicodeText = "UnicodeText";

	/// <summary>Specifies the HTML text format.</summary>
	public const string Html = "HTML Format";

	/// <summary>Specifies the rich text format (RTF).</summary>
	public const string Rtf = "Rich Text Format";

	/// <summary>Specifies the bitmap image format.</summary>
	public const string Bitmap = "Bitmap";

	/// <summary>Specifies the XAML format.</summary>
	public const string Xaml = "Xaml";

	/// <summary>Specifies the XAML package format.</summary>
	public const string XamlPackage = "XamlPackage";

	/// <summary>Specifies a file drop list.</summary>
	public const string FileDrop = "FileDrop";

	/// <summary>Specifies OEM text format.</summary>
	public const string OemText = "OEMText";

	/// <summary>Specifies the Windows metafile picture format.</summary>
	public const string MetafilePicture = "MetaFilePict";

	/// <summary>Specifies the symbolic link data format.</summary>
	public const string SymbolicLink = "SymbolicLink";

	/// <summary>Specifies the Data Interchange Format (DIF).</summary>
	public const string Dif = "DataInterchangeFormat";

	/// <summary>Specifies the Tagged Image File Format (TIFF).</summary>
	public const string Tiff = "TIFF";

	/// <summary>Specifies the pen data format.</summary>
	public const string PenData = "PenData";

	/// <summary>Specifies the RIFF audio format.</summary>
	public const string Riff = "RiffAudio";

	/// <summary>Specifies the wave audio format.</summary>
	public const string WaveAudio = "WaveAudio";

	/// <summary>Specifies the enhanced metafile format.</summary>
	public const string EnhancedMetafile = "EnhancedMetafile";

	/// <summary>Specifies the Windows palette format.</summary>
	public const string Palette = "Palette";

	/// <summary>Specifies the locale ID format.</summary>
	public const string Locale = "Locale";

	/// <summary>Specifies a serializable object format.</summary>
	public const string Serializable = "PersistentObject";

	/// <summary>Specifies the comma-separated values (CSV) format.</summary>
	public const string CommaSeparatedValue = "CSV";

	/// <summary>Specifies a string format (identical to <see cref="UnicodeText"/>).</summary>
	public const string StringFormat = "System.String";
}
