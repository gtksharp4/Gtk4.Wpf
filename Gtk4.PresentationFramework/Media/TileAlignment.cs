namespace System.Windows.Media;

/// <summary>Horizontal content position in a tile. Mirrors <c>System.Windows.Media.AlignmentX</c>.</summary>
public enum AlignmentX
{
	/// <summary>Aligned to the left edge.</summary>
	Left,
	/// <summary>Aligned to the center.</summary>
	Center,
	/// <summary>Aligned to the right edge.</summary>
	Right,
}

/// <summary>Vertical content position in a tile. Mirrors <c>System.Windows.Media.AlignmentY</c>.</summary>
public enum AlignmentY
{
	/// <summary>Aligned to the top edge.</summary>
	Top,
	/// <summary>Aligned to the center.</summary>
	Center,
	/// <summary>Aligned to the bottom edge.</summary>
	Bottom,
}
