namespace System.Windows;

/// <summary>How an inline is aligned to the baseline of its line.</summary>
public enum BaselineAlignment
{
	/// <summary>Aligned at the top of the line.</summary>
	Top,
	/// <summary>Aligned at the center of the line.</summary>
	Center,
	/// <summary>Aligned at the bottom of the line.</summary>
	Bottom,
	/// <summary>Aligned at the baseline.</summary>
	Baseline,
	/// <summary>Aligned at the top of the text.</summary>
	TextTop,
	/// <summary>Aligned at the bottom of the text.</summary>
	TextBottom,
	/// <summary>Aligned at the subscript position.</summary>
	Subscript,
	/// <summary>Aligned at the superscript position.</summary>
	Superscript,
}
