namespace System.Windows.Controls.Primitives;

/// <summary>Where a slider's auto tooltip appears while the thumb is dragged.</summary>
public enum AutoToolTipPlacement
{
	/// <summary>No tooltip.</summary>
	None,
	/// <summary>Above a horizontal slider, left of a vertical one.</summary>
	TopLeft,
	/// <summary>Below a horizontal slider, right of a vertical one.</summary>
	BottomRight,
}
