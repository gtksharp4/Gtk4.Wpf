namespace System.Windows;

/// <summary>Specifies the logical direction of a <see cref="Documents.TextPointer"/>.</summary>
public enum LogicalDirection
{
	/// <summary>Backward: the pointer sticks to the content before it.</summary>
	Backward = 0,

	/// <summary>Forward: the pointer sticks to the content after it.</summary>
	Forward = 1,
}
